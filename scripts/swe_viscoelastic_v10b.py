#!/usr/bin/env python3
"""Kelvin-Voigt SWE viscoelastic analysis for WavePINN v10b outputs.

Inputs
------
`outputs/swe_publication_v10b/swe_metrics_all_samples.csv` generated by
`scripts/swe_publication_v10b.py`.

Model
-----
Kelvin-Voigt complex modulus:

    G*(w) = G_e + i w eta

with known quasi-static elastic shear modulus G_e (from phantom nominal
stiffness) and measured shear-wave speed c_s.

Using the exact phase-velocity relation for KV media:

    c_s^2 = 2 |G*|^2 / (rho (|G*| + G_e))

solve for |G*| (positive root), then:

    eta = sqrt(|G*|^2 - G_e^2) / w

Derived SWE parameters:
  - Dynamic shear modulus: G_dyn = rho c_s^2 (kPa)
  - Dynamic Young's modulus: E_dyn = 3 G_dyn (kPa)
  - Storage modulus: G' = G_e (kPa)
  - Loss modulus: G'' = w eta (kPa)
  - Loss tangent: tan(delta) = G'' / G'

Notes
-----
1) eta depends on the assumed SWE push frequency f_push (default 400 Hz).
2) KV inversion is reported only for 2FT/3FT where quasi-static phantom
   modulus is specified here. Other sources are left as NaN.

Usage
-----
python scripts/swe_viscoelastic_v10b.py
python scripts/swe_viscoelastic_v10b.py \
  --metrics_csv outputs/swe_publication_v10b/swe_metrics_all_samples.csv \
  --output_dir outputs/swe_viscoelastic_v10b \
  --f_push_hz 400
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.stats import pearsonr


RHO = 1000.0  # kg/m^3

# Quasi-static phantom nominal values:
# 2FT: E ~= 2 kPa, 3FT: E ~= 3 kPa, assuming incompressible E = 3G.
G_STATIC_PA = {
    "2ft": 2000.0 / 3.0,
    "3ft": 3000.0 / 3.0,
}

COND_500 = "500Hz_gt"
COND_REF = "5kHz_gt"
COND_PRED = "v10b_6kHz"

COND_LABEL = {
    COND_500: "GT 500 Hz",
    COND_REF: "GT 5 kHz",
    COND_PRED: "Pred 6 kHz (WavePINN v10b)",
}

COND_ORDER = [COND_500, COND_REF, COND_PRED]

COLORS = {
    COND_500: "#D6604D",
    COND_REF: "#2166AC",
    COND_PRED: "#4DAC26",
}


def kv_invert(cs_m_s: float, source: str, f_push_hz: float):
    """Invert Kelvin-Voigt model for one cs estimate."""
    out_nan = {
        "G_prime_kpa": np.nan,
        "eta_Pas": np.nan,
        "G_loss_kpa": np.nan,
        "G_star_kpa": np.nan,
        "tan_delta": np.nan,
        "E_kv_kpa": np.nan,
    }

    if not np.isfinite(cs_m_s) or cs_m_s <= 0:
        return out_nan

    source = str(source).lower()
    if source not in G_STATIC_PA:
        return out_nan

    G_e = float(G_STATIC_PA[source])  # Pa
    omega = 2.0 * np.pi * float(f_push_hz)
    if omega <= 0:
        return out_nan

    cs2rho = (cs_m_s ** 2) * RHO

    # 2y^2 - cs^2 rho y - cs^2 rho G_e = 0, y = |G*|
    disc = cs2rho ** 2 + 8.0 * cs2rho * G_e
    if disc < 0:
        return out_nan

    g_star_pa = (cs2rho + np.sqrt(disc)) / 4.0
    visc_term_sq = g_star_pa ** 2 - G_e ** 2
    if visc_term_sq < 0:
        return out_nan

    eta = np.sqrt(visc_term_sq) / omega

    # Plausibility window for soft-tissue SWE (broad, non-restrictive).
    if not np.isfinite(eta) or eta <= 0 or eta > 100:
        return out_nan

    g_loss_pa = omega * eta
    g_prime_kpa = G_e / 1000.0
    g_loss_kpa = g_loss_pa / 1000.0
    g_star_kpa = g_star_pa / 1000.0
    tan_delta = g_loss_kpa / g_prime_kpa if g_prime_kpa > 0 else np.nan

    return {
        "G_prime_kpa": g_prime_kpa,
        "eta_Pas": float(eta),
        "G_loss_kpa": g_loss_kpa,
        "G_star_kpa": g_star_kpa,
        "tan_delta": tan_delta,
        "E_kv_kpa": 3.0 * g_prime_kpa,
    }


def add_viscoelastic_columns(df: pd.DataFrame, f_push_hz: float) -> pd.DataFrame:
    df = df.copy()

    # Dynamic SWE moduli directly from measured cs.
    df["G_dyn_kpa"] = (RHO * (df["cs_m_s"] ** 2)) / 1000.0
    df["E_dyn_kpa"] = 3.0 * df["G_dyn_kpa"]

    for col in ["G_prime_kpa", "eta_Pas", "G_loss_kpa", "G_star_kpa", "tan_delta", "E_kv_kpa"]:
        df[col] = np.nan

    for i, row in df.iterrows():
        vals = kv_invert(row.get("cs_m_s", np.nan), row.get("source", ""), f_push_hz=f_push_hz)
        for k, v in vals.items():
            df.at[i, k] = v

    return df


def pair_group_means(df: pd.DataFrame, value_col: str):
    """Pair 5kHz GT and v10b group means for agreement analysis."""
    xs = []
    ys = []
    groups = []

    for g in sorted(df["group"].dropna().unique()):
        sub = df[df["group"] == g]
        ref = sub[sub["condition"] == COND_REF][value_col].dropna()
        pred = sub[sub["condition"] == COND_PRED][value_col].dropna()
        if len(ref) == 0 or len(pred) == 0:
            continue
        xs.append(float(ref.mean()))
        ys.append(float(pred.mean()))
        groups.append(g)

    return np.asarray(xs, dtype=float), np.asarray(ys, dtype=float), groups


def summarize_col(series: pd.Series):
    vals = series.dropna().to_numpy(dtype=float)
    if vals.size == 0:
        return "N/A"
    if vals.size == 1:
        return f"{vals.mean():.3f} (n=1)"
    return f"{vals.mean():.3f} +/- {vals.std():.3f}"


def make_bar_figure(df: pd.DataFrame, out_dir: Path):
    """Create SWE-specific visualization for Young's modulus and viscosity."""
    fig, axes = plt.subplots(1, 2, figsize=(12, 5), constrained_layout=True)
    fig.suptitle(
        "SWE Kelvin-Voigt Parameters (v10b): Dynamic Young's Modulus and Viscosity",
        fontsize=12,
        fontweight="bold",
    )

    sources = [s for s in ["2ft", "3ft"] if s in set(df["source"].astype(str).str.lower())]
    source_labels = {"2ft": "2FT (~2 kPa)", "3ft": "3FT (~3 kPa)"}

    params = [
        ("E_dyn_kpa", "Dynamic Young's modulus E_dyn (kPa)"),
        ("eta_Pas", "Kelvin-Voigt viscosity eta (Pa.s)"),
    ]

    for ax, (col, ylabel) in zip(axes, params):
        x_base = np.arange(len(sources), dtype=float)
        width = 0.22
        offsets = np.array([-width, 0.0, width])

        for oi, cond in enumerate(COND_ORDER):
            means = []
            errs = []
            xpos = x_base + offsets[oi]

            for src in sources:
                vals = df[(df["source"] == src) & (df["condition"] == cond)][col].dropna().to_numpy(dtype=float)
                if vals.size == 0:
                    means.append(np.nan)
                    errs.append(np.nan)
                else:
                    means.append(float(np.mean(vals)))
                    errs.append(float(np.std(vals, ddof=1) / np.sqrt(vals.size)) if vals.size > 1 else 0.0)

            means = np.asarray(means, dtype=float)
            errs = np.asarray(errs, dtype=float)
            valid = np.isfinite(means)
            if np.any(valid):
                ax.bar(
                    xpos[valid],
                    means[valid],
                    yerr=errs[valid],
                    width=width * 0.9,
                    capsize=3,
                    color=COLORS[cond],
                    edgecolor="white",
                    alpha=0.9,
                    label=COND_LABEL[cond],
                )

        ax.set_xticks(x_base)
        ax.set_xticklabels([source_labels[s] for s in sources])
        ax.set_ylabel(ylabel)
        ax.grid(True, axis="y", alpha=0.3)
        if col == "E_dyn_kpa":
            ax.set_title("A. Young's modulus")
            ax.legend(fontsize=8)
        else:
            ax.set_title("B. Viscosity")

    for ext in ("png", "pdf"):
        fig.savefig(out_dir / f"fig_kv_young_viscosity_v10b.{ext}", dpi=250)
    plt.close(fig)


def make_scatter_figure(df: pd.DataFrame, out_dir: Path):
    """Agreement scatter: v10b vs 5kHz GT at group level for E_dyn and eta."""
    fig, axes = plt.subplots(1, 2, figsize=(11, 5), constrained_layout=True)
    fig.suptitle("v10b vs 5kHz GT (group means)", fontsize=12, fontweight="bold")

    for ax, (col, unit) in zip(axes, [("E_dyn_kpa", "kPa"), ("eta_Pas", "Pa.s")]):
        x, y, groups = pair_group_means(df, col)
        if x.size < 2:
            ax.set_title(f"{col}: insufficient paired groups")
            continue

        # Color by source family.
        src_map = []
        for g in groups:
            if str(g).lower().startswith("2ft"):
                src_map.append("#4DAC26")
            elif str(g).lower().startswith("3ft"):
                src_map.append("#E66101")
            else:
                src_map.append("#888888")

        ax.scatter(x, y, c=src_map, s=60, edgecolors="white", linewidths=0.6, alpha=0.9)
        lo = min(float(np.min(x)), float(np.min(y))) * 0.9
        hi = max(float(np.max(x)), float(np.max(y))) * 1.1
        ax.plot([lo, hi], [lo, hi], "k--", lw=1)

        r, p = pearsonr(x, y)
        mae = float(np.mean(np.abs(y - x)))
        bias = float(np.mean(y - x))
        rmse = float(np.sqrt(np.mean((y - x) ** 2)))

        ax.text(
            0.03,
            0.97,
            f"r={r:.3f}, p={p:.2e}\nMAE={mae:.3f} {unit}\nRMSE={rmse:.3f} {unit}\nBias={bias:+.3f} {unit}",
            transform=ax.transAxes,
            va="top",
            fontsize=8,
            bbox=dict(boxstyle="round,pad=0.3", facecolor="white", alpha=0.85),
        )

        ax.set_xlabel(f"GT 5 kHz {col} ({unit})")
        ax.set_ylabel(f"Pred 6 kHz {col} ({unit})")
        ax.set_title(col)
        ax.grid(True, alpha=0.3)

    for ext in ("png", "pdf"):
        fig.savefig(out_dir / f"fig_kv_scatter_v10b.{ext}", dpi=250)
    plt.close(fig)


def write_report(df: pd.DataFrame, out_dir: Path, f_push_hz: float):
    lines = []
    p = lines.append
    sep = "=" * 88

    p(sep)
    p("KELVIN-VOIGT SWE VISCOELASTIC REPORT (WavePINN v10b)")
    p(sep)
    p("")
    p("Model:")
    p("  G*(w) = G_e + i w eta")
    p("  c_s^2 = 2|G*|^2 / (rho (|G*| + G_e))")
    p("  eta = sqrt(|G*|^2 - G_e^2) / w")
    p("")
    p(f"Assumptions: rho={RHO:.0f} kg/m^3, f_push={f_push_hz:.1f} Hz")
    p("Phantom quasi-static priors: 2FT E~2kPa, 3FT E~3kPa (E=3G)")
    p("")

    # Overall table by condition.
    header = f"{'Condition':<34} {'n(E)':>6} {'E_dyn (kPa)':>18} {'n(eta)':>8} {'eta (Pa.s)':>16}"
    p(header)
    p("-" * len(header))
    for cond in COND_ORDER:
        sub = df[df["condition"] == cond]
        e = sub["E_dyn_kpa"].dropna()
        eta = sub["eta_Pas"].dropna()
        p(
            f"{COND_LABEL[cond]:<34} {len(e):>6d} {summarize_col(e):>18} "
            f"{len(eta):>8d} {summarize_col(eta):>16}"
        )

    p("")
    p("Per-phantom summary (2FT / 3FT):")
    for src in ["2ft", "3ft"]:
        if src not in set(df["source"].astype(str).str.lower()):
            continue
        p("")
        p(f"{src.upper()}:")
        for cond in COND_ORDER:
            sub = df[(df["source"] == src) & (df["condition"] == cond)]
            p(
                f"  {COND_LABEL[cond]:<30} "
                f"E_dyn={summarize_col(sub['E_dyn_kpa']):<18} "
                f"eta={summarize_col(sub['eta_Pas'])}"
            )

    p("")
    p("Agreement (v10b vs GT 5kHz) on group means:")
    for col, unit in [("E_dyn_kpa", "kPa"), ("eta_Pas", "Pa.s")]:
        x, y, _ = pair_group_means(df, col)
        if x.size < 2:
            p(f"  {col}: insufficient paired groups")
            continue
        r, pv = pearsonr(x, y)
        mae = float(np.mean(np.abs(y - x)))
        rmse = float(np.sqrt(np.mean((y - x) ** 2)))
        bias = float(np.mean(y - x))
        p(
            f"  {col}: N={x.size}, r={r:.4f} (p={pv:.3e}), "
            f"MAE={mae:.4f} {unit}, RMSE={rmse:.4f} {unit}, Bias={bias:+.4f} {unit}"
        )

    p("")
    p("Scientific note:")
    p("  eta is frequency-dependent and inversely scales with assumed f_push")
    p("  through eta = sqrt(|G*|^2 - G_e^2) / (2*pi*f_push).")
    p("  Report f_push alongside eta values for reproducibility.")
    p(sep)

    report_path = out_dir / "kv_viscoelastic_report_v10b.txt"
    with open(report_path, "w") as f:
        f.write("\n".join(lines) + "\n")

    print(f"Saved: {report_path}")


def run(metrics_csv: Path, output_dir: Path, f_push_hz: float):
    if not metrics_csv.exists():
        raise FileNotFoundError(
            f"Missing metrics CSV: {metrics_csv}. Run swe_publication_v10b.py first."
        )

    output_dir.mkdir(parents=True, exist_ok=True)

    df = pd.read_csv(metrics_csv)
    needed = {"condition", "name", "group", "source", "cs_m_s"}
    missing = sorted(list(needed - set(df.columns)))
    if missing:
        raise ValueError(f"Missing required columns in metrics CSV: {missing}")

    df = add_viscoelastic_columns(df, f_push_hz=f_push_hz)

    out_csv = output_dir / "swe_kv_metrics_v10b.csv"
    df.to_csv(out_csv, index=False)
    print(f"Saved: {out_csv}")

    make_bar_figure(df, output_dir)
    print(f"Saved: {output_dir / 'fig_kv_young_viscosity_v10b.png'}")
    print(f"Saved: {output_dir / 'fig_kv_young_viscosity_v10b.pdf'}")

    make_scatter_figure(df, output_dir)
    print(f"Saved: {output_dir / 'fig_kv_scatter_v10b.png'}")
    print(f"Saved: {output_dir / 'fig_kv_scatter_v10b.pdf'}")

    write_report(df, output_dir, f_push_hz=f_push_hz)


def parse_args():
    ap = argparse.ArgumentParser(description="Kelvin-Voigt viscoelastic analysis for v10b SWE")
    ap.add_argument(
        "--metrics_csv",
        type=Path,
        default=Path("outputs/swe_publication_v10b/swe_metrics_all_samples.csv"),
    )
    ap.add_argument(
        "--output_dir",
        type=Path,
        default=Path("outputs/swe_viscoelastic_v10b"),
    )
    ap.add_argument(
        "--f_push_hz",
        type=float,
        default=400.0,
        help="Assumed SWE push frequency for KV inversion.",
    )
    return ap.parse_args()


if __name__ == "__main__":
    args = parse_args()
    run(args.metrics_csv, args.output_dir, args.f_push_hz)
